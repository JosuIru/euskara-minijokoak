/// Categoría semántica de una palabra. Sirve para que el generador de
/// rondas pueda elegir plantillas de frase coherentes (no encajar
/// "kafea" en una plantilla de "vivir en …", por ejemplo).
enum CategoriaSemantica {
  persona,
  animal,
  lugar,
  toponimo,
  objeto,
  alimento,
  // Categorías nuevas para subir a B1-C1: nos permite escribir plantillas
  // con vocabulario abstracto, ámbito profesional/institucional y
  // periodos temporales sin meter en una frase administrativa una manzana.
  abstrakto,
  instituzio,
  denbora,
}

/// Una ficha del banco de palabras. Llevamos las 8 formas declinadas
/// escritas a mano para no caer en errores que un generador "regular"
/// no sabría manejar (consonantes finales, topónimos, asimilaciones,
/// terminación en -a vs -e/-i/-o/-u).
class FichaPalabra {
  final String raizMostrable;
  final String traduccionEspanol;
  final List<CategoriaSemantica> categorias;
  final Map<CasoDeklinabidea, String> formas;

  /// Nivel MCER mínimo en el que esta palabra entra en juego. El
  /// generador filtra para que un alumno de A2 no se encuentre con
  /// vocabulario C1 administrativo o abstracto.
  final NivelEuskera nivel;

  const FichaPalabra({
    required this.raizMostrable,
    required this.traduccionEspanol,
    required this.categorias,
    required this.formas,
    this.nivel = NivelEuskera.a1,
  });

  bool perteneceA(CategoriaSemantica categoria) =>
      categorias.contains(categoria);
}

